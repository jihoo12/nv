local M = {}

function M.setup(plugins)
  local function map(mode, key, fn, desc) vim.keymap.set(mode, key, fn, { desc = desc, silent = true }) end
  map('n', '<Esc>', '<cmd>nohlsearch<cr>', 'Clear search highlight')
  map('n', '<leader>w', '<cmd>write<cr>', 'Save file')
  map('n', '<leader>q', '<cmd>confirm quit<cr>', 'Quit window')
  map('n', '<leader>cf', require('nv.actions').format, 'Format buffer')
  map('n', '<leader>cd', vim.diagnostic.open_float, 'Line diagnostics')
  map('n', '<leader>cq', vim.diagnostic.setqflist, 'Diagnostics to quickfix')
  map('n', '<leader>uh', '<cmd>checkhealth nv<cr>', 'NV health')
  map('n', '<leader>un', function() vim.wo.relativenumber = not vim.wo.relativenumber end, 'Toggle relative numbers')
  map('n', '<leader>uw', function() vim.wo.wrap = not vim.wo.wrap end, 'Toggle line wrap')
  map('n', '<leader>t', require('nv.terminal').toggle, 'Floating terminal')
  map('t', '<C-\\><C-\\>', function()
    vim.cmd.stopinsert()
    require('nv.terminal').toggle()
  end, 'Hide terminal')
  map('t', '<C-/>', function()
    vim.cmd.stopinsert()
    require('nv.terminal').toggle()
  end, 'Hide terminal')
  map('n', '<C-\\>', function()
    vim.cmd.stopinsert()
    require('nv.terminal').toggle()
  end, 'Toggle terminal')
  map('n', '<C-h>', '<C-w>h', 'Window left')
  map('n', '<C-j>', '<C-w>j', 'Window below')
  map('n', '<C-k>', '<C-w>k', 'Window above')
  map('n', '<C-l>', '<C-w>l', 'Window right')
  map('n', '<leader>bn', '<cmd>bnext<cr>', 'Next buffer')
  map('n', '<leader>bp', '<cmd>bprevious<cr>', 'Previous buffer')
  map({ 'n', 'x' }, '<leader>y', '"+y', 'Copy to system clipboard')
  map({ 'n', 'x' }, '<leader>p', '"+p', 'Paste from system clipboard')
  if not plugins then return end
  local pick, extra = require('mini.pick'), require('mini.extra')
  map('n', '<leader>ff', function() pick.builtin.files({}, { source = { cwd = require('nv.actions').root() } }) end, 'Find project files')
  map('n', '<leader>fg', function()
    if vim.fn.executable('rg') == 0 then
      vim.notify('NV: install ripgrep to search project contents.', vim.log.levels.WARN)
      return
    end
    pick.builtin.grep_live({}, { source = { cwd = require('nv.actions').root() } })
  end, 'Search project text')
  map('n', '<leader>fb', pick.builtin.buffers, 'Find buffers')
  map('n', '<leader>fh', pick.builtin.help, 'Find help')
  map('n', '<leader>fr', extra.pickers.oldfiles, 'Recent files')
  map('n', '<leader>fd', extra.pickers.diagnostic, 'Find diagnostics')
  map('n', '<leader>fk', extra.pickers.keymaps, 'Find keymaps')
  map('n', '<leader>e', function()
    local file = vim.api.nvim_buf_get_name(0)
    require('mini.files').open(vim.uv.fs_stat(file) and file or require('nv.actions').root())
  end, 'File explorer')
  map('n', '<leader>bd', function() require('mini.bufremove').delete() end, 'Delete buffer, keep layout')
  map('n', '<leader>gg', function() vim.cmd('Git status') end, 'Git status')
  map('n', '<leader>gl', extra.pickers.git_commits, 'Git commits')
  map('n', '<leader>gf', extra.pickers.git_files, 'Git files')
  map('n', '<leader>gh', extra.pickers.git_hunks, 'Git hunks')
  map('n', '<leader>gd', function() require('mini.diff').toggle_overlay() end, 'Toggle Git diff overlay')
end

return M
